import io

P = "D:/workspace/renwudiaoduqi/docs/Agent任务调度器-开发文档/04-执行/20-里程碑与交付顺序.md"
s = io.open(P, encoding="utf-8").read()

# build_docs.py 用 fullmatch(r"(第.{1,3}批|B\d+)") 认批次行。
# 表头首格写成「第一批」会被当成唯一一条数据行，六个真批次全被 `· 昵称` 后缀挡在外面
# ——阅读器于是只认到 1 个批次，交接台的窗口排程与「首批可并行多少」全部失真。
# 表头首格改「批次」，数据行首格改纯编号，昵称移进可演示列。
pairs = [
    ("| 第一批 | 模块 | 人天 | 结束时可演示 |",
     "| 批次 | 模块 | 人天 | 结束时可演示 |"),
    ("| 第一批 · 跑起来 | M1 | 12.5 | daemon 能启动",
     "| 第一批 | M1 | 12.5 | **跑起来**——daemon 能启动"),
    ("| 第二批 · 连得上 | M2, M3 | 17.0 | 用 curl 完成配对",
     "| 第二批 | M2, M3 | 17.0 | **连得上**——用 curl 完成配对"),
    ("| 第三批 · 派得出去 | M4, M5 | 24.5 | **四个 agent 各派一个真任务并跑完**",
     "| 第三批 | M4, M5 | 24.5 | **派得出去**——四个 agent 各派一个真任务并跑完"),
    ("| 第四批 · 看得见 | M6 | 13.5 | 完整的运行状态机跑通",
     "| 第四批 | M6 | 13.5 | **看得见**——完整的运行状态机跑通"),
    ("| 第五批 · 自动起来 | M7, M8 | 13.0 | **半自动跑完一整批**：",
     "| 第五批 | M7, M8 | 13.0 | **自动起来**——半自动跑完一整批："),
    ("| 第六批 · 两个端 | M9, M10 | 35.0 | 桌面端多流并置",
     "| 第六批 | M9, M10 | 35.0 | **两个端**——桌面端多流并置"),
]
for a, b in pairs:
    if a not in s:
        raise SystemExit("ANCHOR MISSING:\n---\n%s\n---" % a)
    s = s.replace(a, b, 1)

io.open(P, "w", encoding="utf-8", newline="\n").write(s)
print("patched 20-里程碑与交付顺序.md")
